"""Hermetic rendering of a frozen Python graph; no host-Python resolution.

The checked-in JSON records the existing reviewed pins and distribution hashes.
Only the actual guest selects wheels and evaluates markers/Requires-Python.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import tomllib
import zipfile
from email.parser import BytesParser
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SHA = re.compile(r"[0-9a-f]{64}\Z")


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def load(path=HERE / "python-lock.json"):
    if path.is_symlink() or not path.is_file():
        raise ValueError("missing/unsafe frozen Python graph")
    value = json.loads(path.read_bytes())
    if (not isinstance(value, dict) or set(value) != {"schema", "requires_python", "packages"}
            or value["schema"] != 1 or not isinstance(value["requires_python"], str)
            or not isinstance(value["packages"], list) or not value["packages"]):
        raise ValueError("invalid frozen Python graph schema")
    names = []
    for row in value["packages"]:
        if (not isinstance(row, dict) or set(row) != {"name", "version", "hashes"}
                or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", str(row["name"]))
                or not re.fullmatch(r"[0-9][A-Za-z0-9.+!_-]*", str(row["version"]))
                or not isinstance(row["hashes"], list) or not row["hashes"]
                or row["hashes"] != sorted(set(row["hashes"]))
                or any(not isinstance(s, str) or SHA.fullmatch(s) is None for s in row["hashes"])):
            raise ValueError("invalid frozen Python distribution record")
        names.append(row["name"])
    if names != sorted(set(names)):
        raise ValueError("frozen Python graph has duplicate/unsorted names")
    return value


def render(value):
    header = ["# Generated by python infra/workstation/image/golden_lock.py",
              "# Frozen pins, independent of the development interpreter.",
              "# Wheel tags and Requires-Python are verified in the actual Kali guest.",
              "# Acquisition requires hashes; installation uses --no-index.", ""]
    rows = []
    for item in value["packages"]:
        rows.append(item["name"] + "==" + item["version"] + " \\\n" +
                    " \\\n".join("    --hash=sha256:" + sha for sha in item["hashes"]))
    return "\n".join(header + rows) + "\n"


def validate_project(value, project):
    from packaging.requirements import Requirement
    from packaging.specifiers import SpecifierSet
    from packaging.utils import canonicalize_name
    from packaging.version import Version
    data = tomllib.loads(project.read_text())["project"]
    if data["requires-python"] != value["requires_python"]:
        raise ValueError("project/frozen graph Python ranges differ")
    SpecifierSet(value["requires_python"])
    pins = {r["name"]: r for r in value["packages"]}
    for text in data["dependencies"]:
        req = Requirement(text)
        row = pins.get(canonicalize_name(req.name))
        if req.url or req.marker or row is None or Version(row["version"]) not in req.specifier:
            raise ValueError("direct dependency is absent/incompatible in frozen graph: " + text)


def snapshot_from_wheels(value, directory):
    """Read hash-locked wheel metadata only; never infer target tags from it."""
    from packaging.utils import canonicalize_name
    directory = Path(directory)
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("metadata reference wheel directory is missing/unsafe")
    pins = {row["name"]: row for row in value["packages"]}
    hashes = {sha: row for row in value["packages"] for sha in row["hashes"]}
    result = {}
    for path in sorted(directory.glob("*.whl")):
        if path.is_symlink() or not path.is_file():
            raise ValueError("unsafe metadata reference wheel")
        raw = path.read_bytes()
        artifact_sha = hashlib.sha256(raw).hexdigest()
        pin = hashes.get(artifact_sha)
        if pin is None:
            raise ValueError("reference wheel hash is outside the frozen graph: " + path.name)
        with zipfile.ZipFile(path) as wheel:
            names = [name for name in wheel.namelist() if name.endswith(".dist-info/METADATA")]
            if len(names) != 1:
                raise ValueError("reference wheel has no unique METADATA")
            metadata = wheel.read(names[0])
        fields = BytesParser().parsebytes(metadata)
        name = canonicalize_name(fields["Name"])
        if name != pin["name"] or fields["Version"] != pin["version"] or name in result:
            raise ValueError("reference wheel identity differs/duplicates an explicit frozen pin")
        result[name] = {"version": pin["version"], "artifact_sha256": artifact_sha,
            "metadata_sha256": hashlib.sha256(metadata).hexdigest(), "wheel_filename": path.name,
            "requires_python": fields.get("Requires-Python"),
            "requires_dist": sorted(set(fields.get_all("Requires-Dist", [])))}
    if set(result) != set(pins):
        raise ValueError("reference wheel set does not cover the exact frozen graph")
    return {"schema": 1, "distributions": result}


def load_metadata(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError("missing/unsafe frozen dependency metadata")
    value = json.loads(path.read_bytes())
    if (not isinstance(value, dict) or set(value) != {"schema", "distributions"}
            or value["schema"] != 1 or not isinstance(value["distributions"], dict)):
        raise ValueError("invalid frozen dependency metadata schema")
    return value


def validate_metadata(value, snapshot, direct_dependencies=()):
    from packaging.markers import default_environment
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name
    from packaging.version import Version
    pins = {row["name"]: row for row in value["packages"]}
    records = snapshot["distributions"]
    if set(records) != set(pins):
        raise ValueError("frozen metadata graph population differs from locked pins")
    for name, record in records.items():
        if (set(record) != {"version", "artifact_sha256", "metadata_sha256", "wheel_filename", "requires_python", "requires_dist"}
                or record["version"] != pins[name]["version"]
                or record["artifact_sha256"] not in pins[name]["hashes"]
                or SHA.fullmatch(str(record["metadata_sha256"])) is None
                or not isinstance(record["requires_dist"], list)
                or not all(isinstance(text, str) for text in record["requires_dist"])):
            raise ValueError("frozen dependency metadata is not bound to a locked distribution: " + name)
    extras = {name: set() for name in pins}
    for text in direct_dependencies:
        requirement = Requirement(text)
        extras[canonicalize_name(requirement.name)].update(requirement.extras)
    # Only variable NAMES come from packaging. Host marker VALUES never take
    # part in target decisions. Non-extra conditional edges are checked by the
    # actual guest, with the actual wheel/interpreter, during offline install.
    variables = set(default_environment())
    neutral = {name: "" for name in variables}
    changed = True
    while changed:
        changed = False
        for name, record in records.items():
            for text in record["requires_dist"]:
                requirement = Requirement(text)
                if requirement.marker is not None:
                    expression = str(requirement.marker)
                    if any(re.search(r"\b" + variable + r"\b", expression) for variable in variables):
                        continue
                    if not any(requirement.marker.evaluate({**neutral, "extra": extra})
                               for extra in extras[name] or {""}):
                        continue
                dependency = canonicalize_name(requirement.name)
                pin = pins.get(dependency)
                if requirement.url or pin is None or Version(pin["version"]) not in requirement.specifier:
                    raise ValueError("unconditional/extra dependency is absent/incompatible before KVM: " + name + " -> " + text)
                incoming = set(requirement.extras) - extras[dependency]
                if incoming:
                    extras[dependency].update(incoming)
                    changed = True


def check(root=ROOT):
    folder = root / "infra/workstation/image"
    value = load(folder / "python-lock.json")
    validate_project(value, root / "apps/kali-workstation/pyproject.toml")
    project = tomllib.loads((root / "apps/kali-workstation/pyproject.toml").read_text())["project"]
    validate_metadata(value, load_metadata(folder / "python-metadata.json"), project["dependencies"])
    path = folder / "requirements.lock"
    if path.is_symlink() or path.read_text() != render(value):
        raise ValueError("requirements.lock differs from its frozen graph; regenerate it")
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--metadata-from", type=Path,
        help="freeze dependency declarations from one hash-locked reference wheel per pin; no resolution")
    args = parser.parse_args()
    value = load()
    validate_project(value, ROOT / "apps/kali-workstation/pyproject.toml")
    if args.metadata_from is not None:
        snapshot = snapshot_from_wheels(value, args.metadata_from)
        project = tomllib.loads((ROOT / "apps/kali-workstation/pyproject.toml").read_text())["project"]
        validate_metadata(value, snapshot, project["dependencies"])
        (HERE / "python-metadata.json").write_text(json.dumps(snapshot, sort_keys=True, indent=2) + "\n")
    project = tomllib.loads((ROOT / "apps/kali-workstation/pyproject.toml").read_text())["project"]
    validate_metadata(value, load_metadata(HERE / "python-metadata.json"), project["dependencies"])
    if args.check:
        check()
    else:
        (HERE / "requirements.lock").write_text(render(value))


if __name__ == "__main__":
    main()
